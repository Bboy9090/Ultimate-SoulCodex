#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const OUTPUT_DIR = path.resolve(process.cwd(), "dist/public");
const SERVICE_WORKER_PATH = path.join(OUTPUT_DIR, "sw.js");

async function collectFiles(directory, root = directory) {
  const entries = await readdir(directory);
  const files = [];

  for (const entry of entries) {
    const absolutePath = path.join(directory, entry);
    const info = await stat(absolutePath);

    if (info.isDirectory()) {
      files.push(...(await collectFiles(absolutePath, root)));
      continue;
    }

    const relativePath = path.relative(root, absolutePath).split(path.sep).join("/");
    if (relativePath === "sw.js" || relativePath.endsWith(".map")) continue;
    files.push(relativePath);
  }

  return files.sort();
}

async function buildVersion(files) {
  const hash = createHash("sha256");
  for (const file of files) {
    hash.update(file);
    hash.update(await readFile(path.join(OUTPUT_DIR, file)));
  }
  return hash.digest("hex").slice(0, 16);
}

function serviceWorkerSource(files, version) {
  const paths = ["./", ...files.map((file) => `./${file}`)];
  const offlineHtml =
    '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>SoulCodex Offline</title></head><body style="font-family:system-ui;background:#0B0720;color:#fff;padding:2rem"><h1>SoulCodex is offline</h1><p>The application shell was not cached yet. Reconnect once, open SoulCodex, and it will be available offline afterward.</p></body></html>';

  return `/* Generated by scripts/generate-pwa-service-worker.mjs. */
const CACHE_PREFIX = "soulcodex-shell-";
const CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(version)};
const PRECACHE_PATHS = ${JSON.stringify(paths, null, 2)};
const APP_SCOPE = self.registration.scope;
const INDEX_URL = new URL("index.html", APP_SCOPE).href;
const ROOT_URL = new URL("./", APP_SCOPE).href;
const PRECACHE_URLS = PRECACHE_PATHS.map((item) => new URL(item, APP_SCOPE).href);

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

async function networkFirstNavigation(request) {
  const timeout = new Promise((_, reject) => {
    setTimeout(() => reject(new Error("navigation timeout")), 4000);
  });

  try {
    const response = await Promise.race([fetch(request), timeout]);
    if (!response || !response.ok) throw new Error("navigation unavailable");
    const cache = await caches.open(CACHE_NAME);
    await cache.put(INDEX_URL, response.clone());
    return response;
  } catch {
    return (
      (await caches.match(INDEX_URL)) ||
      (await caches.match(ROOT_URL)) ||
      new Response(
        ${JSON.stringify(offlineHtml)},
        { headers: { "Content-Type": "text/html; charset=utf-8" }, status: 503 },
      )
    );
  }
}

async function cacheFirst(request) {
  const cached = await caches.match(request);
  if (cached) return cached;

  const response = await fetch(request);
  if (response.ok) {
    const cache = await caches.open(CACHE_NAME);
    await cache.put(request, response.clone());
  }
  return response;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (/^\\/api(?:\\/|$)/.test(url.pathname)) return;

  if (request.mode === "navigate") {
    event.respondWith(networkFirstNavigation(request));
    return;
  }

  if (["script", "style", "image", "font", "manifest"].includes(request.destination)) {
    event.respondWith(cacheFirst(request));
  }
});

self.addEventListener("message", (event) => {
  if (event.data?.type === "SKIP_WAITING") self.skipWaiting();
});
`;
}

async function main() {
  const files = await collectFiles(OUTPUT_DIR);
  const required = ["index.html", "manifest.webmanifest", "icon-192.png", "icon-512.png"];
  const missing = required.filter((file) => !files.includes(file));
  if (missing.length > 0) {
    throw new Error(`Cannot generate PWA service worker. Missing build assets: ${missing.join(", ")}`);
  }

  const version = await buildVersion(files);
  await writeFile(SERVICE_WORKER_PATH, serviceWorkerSource(files, version), "utf8");
  console.log(`Generated PWA service worker ${version} with ${files.length + 1} precached URLs.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
